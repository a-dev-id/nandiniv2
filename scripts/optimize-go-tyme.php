<?php

// Run with PHP GD: php scripts/optimize-go-tyme.php. Originals are never changed.
$root = dirname(__DIR__);
$target = $root.'/public/images/go-tyme-images/optimized';
if (! is_dir($target)) {
    mkdir($target, 0755, true);
}
$manifest = [];
$content = require $root.'/database/content/go-tyme-retreat.php';
$featuredIds = array_merge([$content['hero']], array_column($content['sections'], 'featured'));
foreach (glob($root.'/public/images/go-tyme-images/*.webp') as $file) {
    $id = substr(basename($file), 3, 5);
    if (in_array($id, ['08537', '08619'], true)) {
        continue;
    }
    $image = imagecreatefromwebp($file);
    $width = imagesx($image);
    $height = imagesy($image);
    foreach ([480, 960, 1600] as $size) {
        if ($size === 1600 && ! in_array($id, $featuredIds, true)) {
            continue;
        }
        $scaledWidth = min($size, $width);
        $scaledHeight = (int) round($height * $scaledWidth / $width);
        $output = $target.'/'.$id.'-'.$size.'.webp';
        if (! is_file($output)) {
            $scaled = imagescale($image, $scaledWidth, $scaledHeight, IMG_BICUBIC_FIXED);
            imagewebp($scaled, $output, 78);
            imagedestroy($scaled);
        }
    }
    $manifest[$id] = ['file' => basename($file), 'width' => $width, 'height' => $height];
    imagedestroy($image);
}
file_put_contents($root.'/database/content/go-tyme-image-dimensions.php', "<?php\n\n// Generated by scripts/optimize-go-tyme.php.\nreturn ".var_export($manifest, true).";\n");
echo count($manifest)." photographs optimized.\n";
